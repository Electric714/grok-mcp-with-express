import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { mkdir } from "node:fs/promises";

const html = await readFile(resolve("ui/dashboard.html"), "utf8");
if (!html.includes("<!-- APP_JS -->")) throw Error("Dashboard script marker not found");
const bundle = await build({
  entryPoints: ["ui/dashboard-client.js"],
  platform: "browser",
  format: "iife",
  target: "es2022",
  bundle: true,
  minify: true,
  write: false,
  logLevel: "warning"
});
const script = bundle.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const result = html.replace("<!-- APP_JS -->", "<script>" + script + "</script>");
const out = resolve("src/generated-dashboard.ts");
await mkdir(dirname(out), { recursive: true });
await writeFile(out, "// Generated by scripts/build-dashboard.mjs. Do not edit.\nexport const dashboardHtml = " + JSON.stringify(result) + ";\n");
console.log("MCP dashboard bundled (" + result.length + " HTML characters)");
